#!/usr/bin/env python3
"""Create .local/clickhouse.yml with a random ClickHouse default password.

The file is ignored by Git and must be passed to Ansible explicitly:

    ./scripts/clickhouse-secret.py
    ansible-playbook clickhouse.yml -i inventory/guests.generated.yml \
      -e @.local/clickhouse.yml

The password is never printed. Use --force only to rotate an existing file.
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
from pathlib import Path

root = Path(__file__).resolve().parent.parent / ".local"
target = root / "clickhouse.yml"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--force", action="store_true", help="rotate the password")
args = parser.parse_args()

root.mkdir(mode=0o700, exist_ok=True)
os.chmod(root, 0o700)

if target.exists() and not args.force:
    print(f"exists: {target} (use --force to rotate)")
    raise SystemExit(0)

password = secrets.token_urlsafe(24)
body = (
    "# Generated by scripts/clickhouse-secret.py; ignored by Git.\n"
    f"clickhouse_password: {json.dumps(password)}\n"
)
target.write_text(body)
os.chmod(target, 0o600)
print(f"created: {target}")
print("run: ansible-playbook clickhouse.yml -i inventory/guests.generated.yml -e @.local/clickhouse.yml")
